def generate_starter_dataset() -> pd.DataFrame:
    """Compile all prompt categories into a clean, balanced, stratified DataFrame."""
    records = []

    # Map categories to list of prompts
    category_prompts = {
        AttackCategory.BENIGN: (BENIGN_PROMPTS, "BENIGN"),
        AttackCategory.DIRECT_PROMPT_INJECTION: (DIRECT_INJECTION_PROMPTS, "ATTACK"),
        AttackCategory.JAILBREAK: (JAILBREAK_PROMPTS, "ATTACK"),
        AttackCategory.SYSTEM_PROMPT_LEAK: (SYSTEM_PROMPT_LEAK_PROMPTS, "ATTACK"),
        AttackCategory.INDIRECT_PROMPT_INJECTION: (INDIRECT_INJECTION_PROMPTS, "ATTACK"),
        AttackCategory.OBFUSCATED_ATTACK: (OBFUSCATED_ATTACK_PROMPTS, "ATTACK"),
        AttackCategory.ROLE_MANIPULATION: (ROLE_MANIPULATION_PROMPTS, "ATTACK"),
        AttackCategory.TOOL_MANIPULATION: (TOOL_MANIPULATION_PROMPTS, "ATTACK"),
        AttackCategory.DATA_EXFILTRATION: (DATA_EXFILTRATION_PROMPTS, "ATTACK"),
        AttackCategory.MULTI_TURN_MANIPULATION: (MULTI_TURN_MANIPULATION_PROMPTS, "ATTACK"),
    }

    for cat_enum, (prompt_list, label_type) in category_prompts.items():
        cat_str = cat_enum.value
        for i, text in enumerate(prompt_list):
            # Deterministic split assignment: 70% train, 15% val, 15% test
            if i % 10 < 7:
                split = "train"
            elif i % 10 < 8:
                split = "val"
            else:
                split = "test"

            records.append({
                "text": text.strip(),
                "label": cat_str,  # multiclass target
                "category": cat_str,
                "is_attack": label_type == "ATTACK",
                "source": "synthetic_seed_v1",
                "split": split,
            })

    df = pd.DataFrame(records)
    # Deduplicate prompts
    df = df.drop_duplicates(subset=["text"]).reset_index(drop=True)
    return df


def save_seed_datasets() -> Dict[str, Path]:
    """Write seed CSVs to backend/data directory."""
    data_dir = settings.DATA_DIR
    data_dir.mkdir(parents=True, exist_ok=True)

    df = generate_starter_dataset()

    prompts_csv = data_dir / "prompts.csv"
    df.to_csv(prompts_csv, index=False, quoting=csv.QUOTE_NONNUMERIC)

    # Save subset files
    benign_csv = data_dir / "benign_prompts.csv"
    df[df["label"] == AttackCategory.BENIGN.value].to_csv(benign_csv, index=False)

    attack_csv = data_dir / "attack_prompts.csv"
    df[df["label"] != AttackCategory.BENIGN.value].to_csv(attack_csv, index=False)

    eval_csv = data_dir / "evaluation_prompts.csv"
    df[df["split"] == "test"].to_csv(eval_csv, index=False)

    return {
        "prompts": prompts_csv,
        "benign": benign_csv,
        "attack": attack_csv,
        "evaluation": eval_csv,
    }


